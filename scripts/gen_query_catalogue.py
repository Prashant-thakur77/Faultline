"""Generate docs/QUERY_CATALOGUE.md from the linted templates (never hand-edit the output).

    PYTHONPATH=backend uv run python scripts/gen_query_catalogue.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from faultline.graph.templates import catalogue  # noqa: E402

GROUPS = [("Gate and proof", r"^Q-(GATE|NEG|INFER)"), ("Impact, scope and lineage", r"^Q-(BLAST|LIN|COL|SUS|CHANGE|RANK|CHOKE|PRIMARY)"),
          ("Alert-storm grouping (INTAKE: group_alerts)", r"^Q-STORM"),
          ("Containment and actions", r"^Q-(CUT|CONN|WHATIF|LEVER|FLAGS|PROTECT|KEEP|ACT|INTENT|CAUSE|WB)"),
          ("People", r"^Q-(ORG|BRAIN-WHO)"),
          ("On-call: who may approve, pages, escalation, standing contracts, shift report",
           r"^Q-(APPROVER|PERSON|ONCALL|PAGE|CONTRACT|SHIFT|HANDOFF)"), ("Obligations (ROUTE: obligation_clock)", r"^Q-OBL"), ("Decisions and knowledge", r"^Q-(DEC|GAP|DOC|FORGET)"),
          ("Company-brain question routing (route_question)", r"^Q-BRAIN-(INTENT|VOCAB)"),
          ("Memory", r"^Q-(MEM|SESS|VEC)"), ("Preflight", r"^Q-PRE"), ("Seeds and lookups", r"^Q-(FIND|CTX|LABELS|META|COUNT|INC)"), ("Schema introspection and engine catalogues", r"^Q-(SCHEMA|FUNCS)"),
          ("Telemetry and baselines", r"^Q-(BASE|MW|SIM|VIEW|ALERT)"), ("Run state, evidence and coordination",
                                                                       r"^Q-(RUN|EV|HYP|CITE|TASK|RUNS)"),
          ("Contrast (evals only, never a decision)", r"^Q-CONTRAST")]


def main() -> int:
    cat = catalogue()
    import json

    latest_path = ROOT / "evals" / "results" / "latest.json"
    latest = json.loads(latest_path.read_text()) if latest_path.exists() else {}
    scratch = {"Q-RANK-1", "Q-ORG-HARM", "Q-ORG-MSF", "Q-STORM-WCC", "Q-STORM-ATTACH"}

    def p50(tid: str, q: str = "p50") -> str:
        key = f"profile.{tid}.engine_ms_{q}"
        if key in latest:  # numbers come only from evals/results/latest.json, tagged for check_claims
            return f"<!-- claim:{key} -->{latest[key]}<!-- /claim -->"
        return "scratch" if tid in scratch else ""
    algo = re.compile(r"(algo\.[A-Za-z]+)|db\.idx\.(vector|fulltext)")
    seen: set[str] = set()
    out = ["# Query catalogue", "", "> GENERATED by `scripts/gen_query_catalogue.py` from `backend/faultline/graph/templates/*.cypher`. "
           "Every product read is one of these templates, run through `graph/ro.py` (GRAPH.RO_QUERY + TIMEOUT + LIMIT n+1). "
           "Template lint: literal LIMIT ≤ 100, ORDER BY, bounded var-length paths, CALL allowlist, no writes.", "",
           "**PROFILE p50 / p95** = engine milliseconds from `GRAPH.PROFILE` (nearest-rank percentiles of 20 runs; `scripts/"
           "profile_templates.py`) for the templates the S1/S2 runs executed, with those runs' recorded params (measured by "
           "the eval harness, read from `evals/results/latest.json`). "
           "Blank = not executed in those runs; `scratch` = runs on a temporary projection.", "",
           f"<!-- claim:repo.templates -->{len(cat)}<!-- /claim --> templates. `{{algo:x}}` is resolved to the procedure name recorded by `make smoke` "
           "(`graph/algo/resolved.json`).", ""]
    for title, rx in GROUPS:
        ids = sorted(t for t in cat if re.match(rx, t) and t not in seen)
        if not ids:
            continue
        out += [f"## {title}", "", "| id | purpose | uses | PROFILE p50 (ms) | p95 (ms) | file |", "|---|---|---|---|---|---|"]
        for tid in ids:
            t = cat[tid]
            uses = sorted({m.group(1) or f"{m.group(2)} index" for m in algo.finditer(t.display)})
            p95 = p50(tid, "p95") if f"profile.{tid}.engine_ms_p95" in latest else ""
            out.append(f"| `{tid}` | {t.purpose.replace('|', '/')} | {', '.join(uses) or 'Cypher'} | {p50(tid)} | {p95} | "
                       f"[{Path(t.path).name}](../backend/faultline/graph/templates/{Path(t.path).name}) |")
            seen.add(tid)
        out.append("")
    rest = sorted(set(cat) - seen)
    if rest:
        out += ["## Other", "", "| id | purpose | file |", "|---|---|---|"]
        out += [f"| `{t}` | {cat[t].purpose.replace('|', '/')} | [{Path(cat[t].path).name}](../backend/faultline/graph/templates/{Path(cat[t].path).name}) |"
                for t in rest]
    (ROOT / "docs" / "QUERY_CATALOGUE.md").write_text("\n".join(out) + "\n")
    print(f"wrote docs/QUERY_CATALOGUE.md ({len(cat)} templates)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
