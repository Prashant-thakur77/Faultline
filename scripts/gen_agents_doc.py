"""Generate docs/AGENTS.md from agent/crew.py and agent/phases.py (never hand-edit the output): the crew's roles, what
each does, the tools its stage whitelist allows (enforced by the ToolBox), what it may write, and whether a model may
drive it. A test keeps the file in step with the code."""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from faultline.agent import crew as C  # noqa: E402
from faultline.agent import phases as P  # noqa: E402

OUT = ROOT / "docs" / "AGENTS.md"


def render() -> str:
    lines = ["# The crew", "",
             "> GENERATED by `scripts/gen_agents_doc.py` from `backend/faultline/agent/crew.py` and `agent/phases.py`. "
             "Every incident is worked by these named, least-privilege roles. Each is deterministic code with its own tool "
             "whitelist enforced by the ToolBox (a call outside it is refused and recorded); only the lead investigator may "
             "use a language model, and the Gatekeeper never does: a model may propose, a read-only query decides. "
             "Each step is a record in FalkorDB: `(:Run)-[:HAS_TASK]->(:Task)-[:CLAIMED_BY]->(:Agent)`, the graph calls it "
             "made (`MADE`), and the hand-off order (`NEXT`); `Q-CREW-1` reads it back and the incident room's Crew board "
             "draws it. Crew records are records, not locks: execution is serialised by the Intent lease, and the gate runs "
             "in every run.", "",
             "| role | job | stages | model | may write | tools |", "|---|---|---|---|---|---|"]
    for m in C.ROSTER:
        model = {"none": "no (deterministic)", "optional": "optional"}[m.model]
        lines.append(f"| **{m.name}** | {m.job} | {', '.join(s.value for s in m.stages)} | {model} | {m.writes} | "
                     + (", ".join(f"`{t}`" for t in m.tools()) or "—") + " |")
    lines += ["", "## The five investigators", "",
              "The lead investigator dispatches them in parallel. Each claims its work item atomically (W-CLAIM-1, fenced "
              "by a claim epoch and renewed on every tool call) and returns a typed contract (`agent/contracts.py`), never "
              "prose; a contract that names an id the run never saw, or cites evidence another run produced, is rejected.",
              "", "| investigator | tools |", "|---|---|"]
    for role, tools in P.SPECIALIST_TOOLS.items():
        lines.append(f"| {role} | " + ", ".join(f"`{t}`" for t in tools) + " |")
    lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    OUT.write_text(render())
    print(f"wrote {OUT.relative_to(ROOT)}")
