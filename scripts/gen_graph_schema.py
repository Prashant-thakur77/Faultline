"""Generate docs/GRAPH_SCHEMA.md from the live graphs + backend/faultline/graph/schema_model.py (never hand-edit).

Labels (counts, property keys, indexes), relationship types (counts, endpoint pairs, lifecycle) and which templates
read each relationship type (a static scan of graph/templates/*.cypher). Reads only through the RO wrapper
(Q-SCHEMA-1..4). By default it reads golden_<t>, the deterministic seeded state, so the document does not change
with every agent run; `--source tenant` reads the live tenant_<t> graphs (runtime nodes and edges included).

    PYTHONPATH=backend uv run python scripts/gen_graph_schema.py [--source golden|tenant] [--out docs/GRAPH_SCHEMA.md]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from faultline.graph import schema_model as M  # noqa: E402
from faultline.graph.algo import registry  # noqa: E402
from faultline.graph.ro import RO  # noqa: E402
from faultline.graph.schema_introspect import drift, introspect, lifecycle, template_rel_usage, tenants_in_engine  # noqa: E402
from faultline.graph.tenant import golden_graph, tenant_graph  # noqa: E402

TEMPLATES = "../backend/faultline/graph/templates"


def _keys(label: str, live: dict[str, dict]) -> str:
    """Union of property keys over the graphs; `key?` = not on every sampled node of the label in some graph."""
    seen: dict[str, bool] = {}
    for s in live.values():
        row = next((x for x in s["labels"] if x["label"] == label), None)
        if not row or not row["sampled"]:
            continue
        for k in row["keys"]:
            full = k["n"] == row["sampled"]
            seen[k["key"]] = seen.get(k["key"], True) and full
    order = sorted(seen, key=lambda k: (k != "id", not seen[k], k))
    return ", ".join(f"`{k}`" if seen[k] else f"`{k}?`" for k in order)


def _indexes(label: str, live: dict[str, dict]) -> str:
    out: set[str] = set()
    for s in live.values():
        row = next((x for x in s["labels"] if x["label"] == label), None)
        for i in (row or {}).get("indexes", []):
            out |= {f"{i['property']} ({t.lower().replace('fulltext', 'full-text')})" for t in i["types"]}
    return ", ".join(sorted(out))


def render(live: dict[str, dict], source: str) -> str:
    usage = template_rel_usage()
    rep = drift(live)
    graphs = list(live)
    short = {g: g.split("_", 1)[1] for g in graphs}
    lines = [
        "# Graph schema",
        "",
        f"> GENERATED by `scripts/gen_graph_schema.py` from the live graphs ({', '.join(f'`{g}`' for g in graphs)}) and "
        "`backend/faultline/graph/schema_model.py`; never hand-edit. "
        + ("`golden_<t>` is the deterministic seeded state (runtime-only types appear once agent runs write them). "
           if source == "golden" else "`tenant_<t>` includes whatever runs have written since the last Re-arm. ")
        + "Counts come from the engine's own statistics (`db.meta.stats`, template Q-SCHEMA-1). Endpoint pairs and "
        "property keys come from bounded scans (Q-SCHEMA-2, Q-SCHEMA-3); a scan is complete when its total equals the "
        "engine's count. Indexes come from `db.indexes` (Q-SCHEMA-4). \"Read by\" is a static scan of "
        "`backend/faultline/graph/templates/*.cypher`. The same data is served live by the `graph_schema` MCP tool and "
        "the `faultline://schema` resource. Drift check: `scripts/check_schema_drift.py`.",
        "",
        f"Engine: FalkorDB {registry.resolved_meta().get('engine', '?')}. Every node carries the base label "
        f"`{M.BASE_LABEL}` (cross-label id lookups) plus exactly one domain label.",
        "",
        "## Summary",
        "",
        "| graph | nodes | edges | labels with nodes | relationship types with edges | endpoint pairs complete | property keys complete |",
        "|---|---|---|---|---|---|---|",
    ]
    for g, s in live.items():
        t, c = s["totals"], s["complete"]
        lines.append(f"| `{g}` | {t['nodes']} | {t['edges']} | {t['labels_present']} | {t['rel_types_present']} | "
                     f"{'yes' if c['pairs'] else 'no (sampled)'} | {'yes' if c['keys'] else 'no (sampled)'} |")
    lines += ["", "## Node labels", "",
              "Counts per graph. `key?` = optional (missing on some sampled nodes). Labels with no nodes in any graph "
              "are listed after the table.", "",
              "| label | " + " | ".join(short[g] for g in graphs) + " | properties | indexes |",
              "|---|" + "---|" * len(graphs) + "---|---|"]
    counts = {g: {x["label"]: x["n"] for x in s["labels"]} for g, s in live.items()}
    all_labels = sorted(M.NODE_LABELS | {x for c in counts.values() for x in c})
    empty = []
    for lab in all_labels:
        ns = [counts[g].get(lab, 0) for g in graphs]
        if not any(ns):
            empty.append(lab)
            continue
        flag = "" if lab in M.NODE_LABELS else " **UNDECLARED**"
        lines.append(f"| `{lab}`{flag} | " + " | ".join(str(n) for n in ns) + f" | {_keys(lab, live)} | {_indexes(lab, live)} |")
    lines += ["", "Declared, no nodes in these graphs (written at runtime, or not yet used): "
              + ", ".join(f"`{x}`" for x in empty) + ".", ""]

    lines += ["## Relationship types", "",
              "Lifecycle: `seed` = written by the ingest producers; `runtime` = written only by runs, actions or write-back "
              "(`schema_model.RUNTIME_RELS`); `scratch` = only in temporary projections; `reserved` = declared in the "
              "model with no writer yet (`schema_model.RESERVED_RELS`).", "",
              "| type | lifecycle | " + " | ".join(short[g] for g in graphs) + " | endpoint pairs (from → to) | read by templates |",
              "|---|---|" + "---|" * len(graphs) + "---|---|"]
    rc = {g: {x["type"]: x for x in s["relationships"]} for g, s in live.items()}
    for rel in sorted(M.REL_TYPES | {x for c in rc.values() for x in c}):
        ns = [rc[g].get(rel, {}).get("n", 0) for g in graphs]
        pairs = sorted({(p["src"], p["dst"]) for g in graphs for p in rc[g].get(rel, {}).get("pairs", [])})
        reads = usage.get(rel, [])
        read_cell = ", ".join(f"`{t}`" for t in reads) or ("**none (write-only)**" if any(ns) else "none")
        lines.append(f"| `{rel}` | {lifecycle(rel)} | " + " | ".join(str(n) for n in ns) + " | "
                     + (", ".join(f"{a} → {b}" for a, b in pairs) or "") + f" | {read_cell} |")
    lines += ["", "## Write-only relationship types", "",
              "Present in a graph but read by no template (no relationship pattern, algo config or `type(r)` test "
              "names them). The ingest producers write them as source provenance; for lineage edges the failure-flow "
              "meaning is materialised at ingest as `PROPAGATES_TO` / `DEPENDS_ON`, which the templates traverse. "
              "Each is a candidate for a template, or for removal.", "",
              (", ".join(f"`{x}`" for x in rep["write_only"]) or "none") + ".", ""]
    if not rep["ok"]:
        lines += ["## DRIFT", ""] + [f"- {f}" for f in rep["failures"]] + [""]
    lines += ["## Indexes", "", "| label | property | kind |", "|---|---|---|"]
    idx: set[tuple[str, str, str]] = set()
    for s in live.values():
        for x in s["labels"]:
            for i in x["indexes"]:
                idx |= {(x["label"], i["property"], t.lower()) for t in i["types"]}
    lines += [f"| `{a}` | `{b}` | {c} |" for a, b, c in sorted(idx)]
    lines += ["", f"Index DDL: `backend/faultline/graph/schema.cypher` (full-text DDL form only; vectors written with "
              f"`vecf32()`). Template files: `{TEMPLATES}/`.", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--source", choices=("golden", "tenant"), default="golden")
    ap.add_argument("--tenant", action="append")
    ap.add_argument("--out", default=str(ROOT / "docs" / "GRAPH_SCHEMA.md"))
    a = ap.parse_args(argv)
    tenants = a.tenant or tenants_in_engine()
    if not tenants:
        print("no tenant graphs found (run `make seed`)", file=sys.stderr)
        return 2
    live = {}
    for t in tenants:
        name = golden_graph(t) if a.source == "golden" else tenant_graph(t)
        live[name] = introspect(RO(t, name))[0]
    Path(a.out).write_text(render(live, a.source))
    print(f"wrote {a.out} ({', '.join(live)})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
