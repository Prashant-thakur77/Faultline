"""Render docs/FALKORDB_COMPAT.md and backend/faultline/graph/algo/resolved.json from smoke runs.

    python scripts/render_compat.py docs/audit/smoke_6.0.2.json docs/audit/smoke_v4.22.0.json --pin 6.0.2
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def cell(r: dict | None) -> str:
    if r is None:
        return "—"
    return {True: "PASS", False: "**FAIL**", None: "info"}[r["ok"]]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("runs", nargs="+")
    ap.add_argument("--pin", required=True, help="tag to pin")
    a = ap.parse_args()
    runs = [json.loads(Path(p).read_text()) for p in a.runs]
    by_tag = {r["tag"]: {x["id"]: x for x in r["results"]} for r in runs}
    tags = [r["tag"] for r in runs]
    pinned = next(r for r in runs if r["tag"] == a.pin)
    ids = [x["id"] for x in runs[0]["results"]]

    lines = [
        "# FalkorDB compatibility (generated by `scripts/render_compat.py` from `make smoke`; do not hand-edit)",
        "",
        f"**Pinned engine: `falkordb/falkordb:{a.pin}` @ `{pinned['digest']}`**.",
        "",
    ]
    for r in runs:
        crit = [x for x in r["results"] if x["critical"]]
        lines.append(
            f"- `{r['tag']}` ({r['digest'][:19]}…): critical **{sum(1 for x in crit if x['ok'])}/{len(crit)}**, "
            f"all {sum(1 for x in r['results'] if x['ok'])}/{len(r['results'])}, ran {r['ran_at']} in {r['seconds']} s"
        )
    lines += ["", "| # | item | C | " + " | ".join(tags) + " |", "|---|---|---|" + "---|" * len(tags)]
    for i in ids:
        base = by_tag[tags[0]][i]
        lines.append(
            f"| {i} | {base['item']} | {'C' if base['critical'] else ''} | "
            + " | ".join(cell(by_tag[t].get(i)) for t in tags) + " |"
        )
    lines += ["", "## Observed behaviour and working syntax (per engine)", ""]
    for i in ids:
        base = by_tag[tags[0]][i]
        lines.append(f"### {i}. {base['item']}")
        if base.get("syntax"):
            lines.append(f"Syntax: `{base['syntax']}`")
        for t in tags:
            lines.append(f"- **{t}**: {by_tag[t][i]['notes']}")
        lines.append("")
    notes = ROOT / "docs" / "compat_notes.md"  # verified by live tests outside smoke (e.g. the official MCP server)
    if notes.exists():
        lines += ["", *[ln for ln in notes.read_text().splitlines() if not ln.startswith("<!--")]]
    Path(ROOT / "docs/FALKORDB_COMPAT.md").write_text("\n".join(lines) + "\n")
    failed = [x["id"] for x in pinned["results"] if x["critical"] and not x["ok"]]
    if failed:
        print(f"refusing to pin {a.pin}: critical items failed: {failed}", file=sys.stderr)
        return 1
    item_of = {"bfs": "2", "sppaths": "3", "sspaths": "4", "pagerank": "5", "betweenness": "6", "harmonic": "7",
               "wcc": "8", "cdlp": "9", "maxflow": "10", "msf": "11"}
    ok_items = {x["id"] for x in pinned["results"] if x["ok"]}
    procs = {k: v for k, v in pinned["resolved"].items() if item_of.get(k) in ok_items}
    resolved = {"engine": a.pin, "digest": pinned["digest"], "module_ver": pinned.get("module_ver"), "procedures": procs}
    out = ROOT / "backend/faultline/graph/algo/resolved.json"
    out.write_text(json.dumps(resolved, indent=2) + "\n")
    print(f"wrote docs/FALKORDB_COMPAT.md and {out.relative_to(ROOT)} ({len(pinned['resolved'])} procedures)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
