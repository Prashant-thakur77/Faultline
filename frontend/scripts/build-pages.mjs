#!/usr/bin/env node
/**
 * npm run build:pages: the static, backend-free replay site for GitHub Pages.
 *
 *   1. checks that the replay bundles exist (public/replay/index.json + each run's required files);
 *   2. refreshes the staging project dir .pages-build/ (see Isolation below);
 *   3. runs `next build` there with FAULTLINE_PAGES=1 (next.config.ts → output: "export", basePath,
 *      trailingSlash, unoptimized images), exporting into out-pages/;
 *   4. checks the export has the landing page, /replay/, each /replay/<run>/ page, the bundles and
 *      a 404.html, that every Next page loads its assets under the base path and that none
 *      references the live API, then writes .nojekyll.
 *
 * Base path: NEXT_PUBLIC_BASE_PATH (default "/Faultline"; "" for a user site or custom domain).
 * Any failure exits non-zero with the reason (fail loudly); nothing is skipped silently.
 *
 * Isolation: `next build` always keeps its scratch files in <project>/.next/, even for an export.
 * So the build runs from a staging project dir, .pages-build/ (git-ignored), whose src/ and
 * public/ are symlinks to the real ones and whose configs are copied from the real ones. The live
 * build's .next/ (and a `next start` serving it) is never touched. The export lands in out-pages/.
 */
import { spawnSync } from "node:child_process";
import { copyFile, lstat, mkdir, readdir, readFile, stat, symlink, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const frontend = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(frontend, "out-pages");
const STAGE = path.join(frontend, ".pages-build");
const RUNS = ["s1-hero", "s2-data-incident"]; // keep in sync with REPLAY_RUNS in src/lib/replay.ts
const REQUIRED = ["events.jsonl", "gate_runs.json", "tool_calls.json", "hypotheses.json", "report.json", "manifest.json"];

const exists = async (p) => !!(await stat(p).catch(() => null));
const fail = (msg) => {
  console.error(`build:pages FAILED: ${msg}`);
  process.exit(1);
};

// 1. Inputs.
const replayRoot = path.join(frontend, "public", "replay");
if (!(await exists(path.join(replayRoot, "index.json")))) fail("public/replay/index.json is missing (run npm run replay:export)");
for (const run of RUNS) {
  for (const f of REQUIRED) {
    if (!(await exists(path.join(replayRoot, run, f)))) fail(`public/replay/${run}/${f} is missing (run npm run replay:export)`);
  }
}

// 2. Staging project dir (idempotent: links and configs are refreshed in place).
await mkdir(STAGE, { recursive: true });
for (const dir of ["src", "public"]) {
  const link = path.join(STAGE, dir);
  const st = await lstat(link).catch(() => null);
  if (st && !st.isSymbolicLink()) fail(`.pages-build/${dir} exists and is not a symlink; move it away and retry`);
  if (!st) await symlink(path.join("..", dir), link, "dir");
}
for (const f of ["package.json", "tsconfig.json", "next.config.ts"]) {
  await copyFile(path.join(frontend, f), path.join(STAGE, f));
}
// Tailwind scans for class names from `base`: point it at the real frontend (it skips
// git-ignored dirs, node_modules included, so it sees src/ exactly as the live build does).
await writeFile(
  path.join(STAGE, "postcss.config.mjs"),
  `// Generated by scripts/build-pages.mjs; edit ../postcss.config.mjs instead.\nexport default { plugins: { "@tailwindcss/postcss": { base: ${JSON.stringify(frontend)} } } };\n`,
);

// 3. Build.
const basePath = (process.env.NEXT_PUBLIC_BASE_PATH ?? "/Faultline").trim().replace(/\/+$/, "");
console.log(`build:pages: static export into out-pages/ with basePath "${basePath || "(none)"}"`);
const nextBin = path.join(frontend, "node_modules", "next", "dist", "bin", "next");
const res = spawnSync(process.execPath, [nextBin, "build"], {
  cwd: STAGE,
  stdio: "inherit",
  env: {
    ...process.env,
    FAULTLINE_PAGES: "1",
    FAULTLINE_PAGES_ROOT: frontend,
    FAULTLINE_PAGES_OUT: path.relative(STAGE, OUT),
    NEXT_PUBLIC_BASE_PATH: basePath,
  },
});
if (res.status !== 0) fail(`next build exited with ${res.status ?? res.signal}`);

// 4. Output checks.
const pages = ["index.html", "404.html", "replay/index.html", ...RUNS.map((r) => `replay/${r}/index.html`)];
for (const p of pages) if (!(await exists(path.join(OUT, p)))) fail(`out-pages/${p} was not generated`);
for (const run of RUNS) {
  for (const f of REQUIRED) if (!(await exists(path.join(OUT, "replay", run, f)))) fail(`out-pages/replay/${run}/${f} was not copied`);
}

async function* htmlFiles(dir) {
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) yield* htmlFiles(p);
    else if (e.name.endsWith(".html")) yield p;
  }
}
const prefix = basePath ? `${basePath}/_next/` : "/_next/";
for await (const file of htmlFiles(OUT)) {
  const html = await readFile(file, "utf8");
  const rel = path.relative(OUT, file);
  // Hand-written files copied from public/ (e.g. media/*.html) are not Next pages.
  if (await exists(path.join(frontend, "public", rel))) continue;
  if (/localhost:8400|\/api\/status/.test(html)) fail(`${rel} references the live API`);
  if (basePath && /(?:src|href)="\/_next\//.test(html)) fail(`${rel} loads assets without the base path ${basePath}`);
  if (!html.includes(prefix)) fail(`${rel} has no ${prefix} assets: the base path was not applied`);
}

// GitHub Pages: never run Jekyll over the export (it drops the _next/ directory).
await writeFile(path.join(OUT, ".nojekyll"), "");
console.log(`build:pages OK: ${pages.length} required pages + ${RUNS.length} replay bundles in out-pages/ (basePath "${basePath || "(none)"}")`);
