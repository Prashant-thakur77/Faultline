/** "Before you run it.": a plain accordion. Panels open with a grid-rows height transition, instant under reduced motion. */
export function Faq() {
  const [open, setOpen] = useState<Set<number>>(() => new Set());
  const base = useId();
  const toggle = (i: number) => setOpen((prev) => {
    const next = new Set(prev);
    if (next.has(i)) next.delete(i); else next.add(i);
    return next;
  });
  return (
    <section id="faq" aria-labelledby="faq-title" className="mx-auto grid max-w-[1200px] scroll-mt-20 gap-10 px-5 py-24 sm:px-8 lg:grid-cols-[minmax(0,5fr)_minmax(0,7fr)] lg:gap-16 lg:py-32">
      <div>
        <p className="font-mono text-[11px] uppercase tracking-[0.3em] text-[var(--fl-subtle)]">Getting started</p>
        <h2 id="faq-title" className="mt-4 text-[clamp(1.9rem,4.2vw,3rem)] font-[510] leading-[1.08] tracking-[-0.022em] text-zinc-50">
          Before you run it.
        </h2>
      </div>
      <div className="border-b border-white/[0.08]">
        {FAQ_ITEMS.map((item, i) => {
          const on = open.has(i);
          const btn = `${base}-q${i}`, panel = `${base}-a${i}`;
          return (
            <div key={item.q} className="border-t border-white/[0.08]">
              <h3>
                <button type="button" id={btn} aria-expanded={on} aria-controls={panel} onClick={() => toggle(i)}
                        className="group flex w-full items-center justify-between gap-6 rounded py-5 text-left text-[17px] font-[510] tracking-[-0.01em] text-zinc-100 outline-none hover:text-white focus-visible:ring-2 focus-visible:ring-sky-400">
                  <span>{item.q}</span>
                  <Plus aria-hidden className={"size-4 shrink-0 text-[var(--fl-muted)] transition-transform duration-300 ease-[var(--fl-ease)] group-hover:text-zinc-200 motion-reduce:transition-none " + (on ? "rotate-45" : "")} />
                </button>
              </h3>
              {/* the grid-rows trick animates to the content's own height; visibility keeps a closed answer out of the tab order and the a11y tree */}
              <div id={panel} role="region" aria-labelledby={btn}
                   className={"grid transition-[grid-template-rows,visibility] duration-300 ease-[var(--fl-ease)] motion-reduce:transition-none " + (on ? "visible grid-rows-[1fr]" : "invisible grid-rows-[0fr]")}>
                <div className="overflow-hidden">
                  <p className="max-w-[60ch] pb-6 pr-10 text-[15px] leading-relaxed text-[var(--fl-muted)]">{item.a}</p>
                </div>
              </div>
            </div>
          );
        })}
      </div>
    </section>
  );
}
